@dataclass(frozen=True)
class Finding:
    path: str
    message: str


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Run read-only docs health checks.")
    parser.add_argument(
        "--strict-frontmatter",
        action="store_true",
        help="Treat missing or incomplete frontmatter as errors.",
    )
    parser.add_argument(
        "--strict-links",
        action="store_true",
        help="Treat broken local markdown links as errors.",
    )
    parser.add_argument(
        "--max-details",
        type=int,
        default=30,
        help="Maximum detailed findings to print for each text section.",
    )
    parser.add_argument(
        "--format",
        choices=("text", "json"),
        default="text",
        help="Output format. JSON includes all findings and ignores --max-details.",
    )
    return parser.parse_args()


def repo_path(path: Path) -> str:
    return path.relative_to(REPO_ROOT).as_posix()


def iter_markdown_files() -> list[Path]:
    active_modules = parse_gradle_modules()
    allowed_prefixes = [
        ("docs",),
        ("dev",),
    ]
    allowed_exact = {
        "AGENTS.md",
        "CLAUDE.md",
        "DESIGN.md",
        "README.md",
    }

    files: list[Path] = []
    for path in REPO_ROOT.rglob("*.md"):
        relative_parts = path.relative_to(REPO_ROOT).parts
        if any(part in HISTORICAL_DIR_PARTS for part in relative_parts):
            continue
        relative = path.relative_to(REPO_ROOT).as_posix()
        if relative in HISTORICAL_MARKDOWN_FILES:
            continue
        if not path.is_file():
            continue

        module_doc = len(relative_parts) >= 3 and relative_parts[0] in active_modules and relative_parts[1] == "docs"
        module_readme = len(relative_parts) == 2 and relative_parts[0] in active_modules and relative_parts[1] == "README.md"
        docs_or_dev = any(relative_parts[: len(prefix)] == prefix for prefix in allowed_prefixes)
        root_doc = len(relative_parts) == 1 and relative in allowed_exact
        if not (module_doc or module_readme or docs_or_dev or root_doc):
            continue

        files.append(path)
    return sorted(files)


def iter_iteration_frontmatter_files() -> list[Path]:
    """Phase logs get frontmatter checks only. Links and stale dates stay off this tree."""
    root = REPO_ROOT / "dev" / "iterations"
    if not root.is_dir():
        return []
    files: list[Path] = []
    for path in root.rglob("*.md"):
        if not path.is_file():
            continue
        if "archive" in path.relative_to(REPO_ROOT).parts:
            continue
        files.append(path)
    return sorted(files)


def parse_gradle_modules(settings_path: Path | None = None) -> list[str]:
    settings = settings_path if settings_path is not None else REPO_ROOT / "settings.gradle.kts"
    modules: list[str] = []
    include_pattern = re.compile(r'include\(":(?P<name>[^"]+)"\)')
    for raw_line in settings.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if line.startswith("//"):
            continue
        match = include_pattern.search(line)
        if match:
            modules.append(match.group("name"))
    return sorted(set(modules))


def check_required_entries() -> list[Finding]:
    findings: list[Finding] = []
    for entry in REQUIRED_DOC_ENTRIES:
        path = REPO_ROOT / entry
        if not path.exists():
            findings.append(Finding(entry, "required documentation entry is missing"))
    return findings


def resolve_status_md(path: Path | None) -> Path:
    return path if path is not None else REPO_ROOT / STATUS_MD_PATH


def status_finding_path(path: Path) -> str:
    try:
        return repo_path(path)
    except ValueError:
        return path.as_posix()


def check_status_md_line_limit(path: Path | None = None) -> list[Finding]:
    status = resolve_status_md(path)
    if not status.exists():
        return []
    line_count = len(status.read_text(encoding="utf-8").splitlines())
    if line_count > STATUS_MD_MAX_LINES:
        return [
            Finding(
                status_finding_path(status),
                f"exceeds {STATUS_MD_MAX_LINES} lines ({line_count}); "
                "move historical detail to dev/progress/status-history-archive.md",
            )
        ]
    return []


def status_body_after_frontmatter(text: str) -> str:
    if not text.startswith("---\n"):
        return text
    end = text.find("\n---\n", 4)
    if end < 0:
        return text
    return text[end + 5 :]


def body_has_snapshot(body: str) -> bool:
    in_run = False
    for line in body.splitlines():
        stripped = line.lstrip()
        if stripped.startswith("> **后注"):
            in_run = True
            continue
        if in_run and stripped.startswith(">"):
            continue
        in_run = False
        if stripped.strip():
            return True
    return False


def check_status_md_snapshot_body(path: Path | None = None) -> list[Finding]:
    status = resolve_status_md(path)
    if not status.exists():
        return []
    body = status_body_after_frontmatter(status.read_text(encoding="utf-8"))
    if body_has_snapshot(body):
        return []
    return [Finding(status_finding_path(status), "缺少快照正文")]


def check_status_md_merge_sha_placeholder(path: Path | None = None) -> list[Finding]:
    status = resolve_status_md(path)
    if not status.exists():
        return []
    findings: list[Finding] = []
    for line in status.read_text(encoding="utf-8").splitlines():
        stripped = line.lstrip()
        if stripped.startswith(">") :
            stripped = stripped[1:].lstrip()
        if stripped.startswith("|") and "$MERGE_SHA" in stripped:
            findings.append(
                Finding(
                    status_finding_path(status),
                    "slot table contains literal $MERGE_SHA; write git rev-parse HEAD hex",
                )
            )
            break
    return findings


def unreadable_markdown_findings() -> list[Finding]:
    active_modules = parse_gradle_modules()
    findings: list[Finding] = []
    for path in REPO_ROOT.rglob("*.md"):
        relative_parts = path.relative_to(REPO_ROOT).parts
        relative = path.relative_to(REPO_ROOT).as_posix()
        if any(part in HISTORICAL_DIR_PARTS for part in relative_parts):
            continue
        if relative in HISTORICAL_MARKDOWN_FILES:
            continue
        if relative_parts[0] not in {"docs", "dev", *active_modules}:
            continue
        if path.exists():
            continue
        findings.append(Finding(repo_path(path), "markdown path exists in traversal but target is not readable"))
    return findings


def normalize_module_table_name(cell: str) -> str:
    name = cell.strip()
    while True:
        stripped = MODULE_TABLE_SUFFIX_RE.sub("", name).strip()
        if stripped == name:
            return name
        name = stripped


def module_names_in_global_index(index_path: Path | None = None) -> set[str]:
    path = index_path if index_path is not None else REPO_ROOT / GLOBAL_MODULE_INDEX
    if not path.exists():
        return set()
    names: set[str] = set()
    in_section = False
    for line in path.read_text(encoding="utf-8").splitlines():
        heading = line.strip()
        if heading.startswith("## "):
            if in_section:
                break
            in_section = heading == "## 模块列表"
            continue
        if not in_section or not heading.startswith("|"):
            continue
        cell = heading.strip("|").split("|", 1)[0].strip()
        if not cell or cell == "模块名" or set(cell) <= {"-", ":"}:
            continue
        name = normalize_module_table_name(cell)
        if name:
            names.add(name)
    return names


def check_module_indexes(
    active_modules: list[str],
    index_path: Path | None = None,
) -> tuple[list[Finding], list[Finding]]:
    errors: list[Finding] = []
    warnings: list[Finding] = []

    for module in active_modules:
        index = REPO_ROOT / "docs" / "modules" / module / "INDEX.md"
        if not index.exists():
            errors.append(Finding(repo_path(index), "active Gradle module has no docs/modules index"))

        readme = REPO_ROOT / module / "README.md"
        if not readme.exists():
            warnings.append(Finding(repo_path(readme), "active Gradle module has no root README.md"))

    listed = module_names_in_global_index(index_path)
    for module in active_modules:
        if module not in listed:
            errors.append(Finding(GLOBAL_MODULE_INDEX, f"{module} 不在全局模块表"))

    return errors, warnings


def frontmatter_findings(markdown_files: list[Path]) -> list[Finding]:
    findings: list[Finding] = []
    for path in markdown_files:
        if repo_path(path) in FRONTMATTER_EXEMPT_FILES:
            continue
        if path.name in FRONTMATTER_EXEMPT_BASENAMES:
            continue

        text = path.read_text(encoding="utf-8", errors="replace")
        lines = text.splitlines()
        if not lines or lines[0].strip() != "---":
            findings.append(Finding(repo_path(path), "missing YAML frontmatter"))
            continue

        try:
            closing = lines[1:].index("---") + 1
        except ValueError:
            findings.append(Finding(repo_path(path), "frontmatter is not closed"))
            continue

        body = "\n".join(lines[1:closing])
        missing_fields = [field for field in REQUIRED_FRONTMATTER_FIELDS if not re.search(rf"^{field}\s*:", body, re.MULTILINE)]
        if missing_fields:
            findings.append(Finding(repo_path(path), "frontmatter missing fields: " + ", ".join(missing_fields)))

        # Body content (post-notes/tables) has repeatedly been merged into the
        # frontmatter block above the YAML fields without any checker noticing;
        # flag the observed corruption signatures.
        for fm_no, fm_line in enumerate(lines[1:closing], start=2):
            if fm_line[:1] in (">", "|"):
                findings.append(Finding(repo_path(path), f"frontmatter contains body content at line {fm_no} (misplaced note/quote/table)"))
                break

        dup_keys = sorted(k for k, c in Counter(re.findall(r"^([\w.-]+)\s*:", body, re.MULTILINE)).items() if c > 1)
        if dup_keys:
            findings.append(Finding(repo_path(path), "frontmatter duplicate keys: " + ", ".join(dup_keys)))

    return findings


GIT_DATE_CACHE: dict[str, str] | None = None
DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")


def git_last_change_dates() -> dict[str, str]:
    """Map repo-relative path -> last commit date (YYYY-MM-DD) across full history."""
    global GIT_DATE_CACHE
    if GIT_DATE_CACHE is not None:
        return GIT_DATE_CACHE
    dates: dict[str, str] = {}
    try:
        proc = subprocess.run(
            ["git", "log", "--name-only", "--date=short", "--format=@@%cd"],
            cwd=REPO_ROOT, capture_output=True, text=True, timeout=120,
        )
    except (OSError, subprocess.SubprocessError):
        GIT_DATE_CACHE = dates
        return dates
    if proc.returncode == 0:
        current: str | None = None
        for line in proc.stdout.splitlines():
            if line.startswith("@@"):
                current = line[2:]
            elif line.strip() and current is not None and line not in dates:
                dates[line] = current
    GIT_DATE_CACHE = dates
    return dates


def gitlink_dirs() -> set[str]:
    """Repo-relative paths of submodule gitlinks (mode 160000); their internals are separate repos."""
    try:
        proc = subprocess.run(
            ["git", "ls-files", "--stage"], cwd=REPO_ROOT, capture_output=True, text=True, timeout=60,
        )
    except (OSError, subprocess.SubprocessError):
        return set()
    if proc.returncode != 0:
        return set()
    dirs = set()
    for line in proc.stdout.splitlines():
        meta, _, name = line.partition("\t")
        if meta.split() and meta.split()[0] == "160000":
            dirs.add(name)
    return dirs


def stale_updated_findings(markdown_files: list[Path]) -> list[Finding]:
    findings: list[Finding] = []
    last_dates = git_last_change_dates()
    if not last_dates:
        return findings
    submodules = gitlink_dirs()
    for path in markdown_files:
        relative = repo_path(path)
        if any(relative == d or relative.startswith(d + "/") for d in submodules):
            continue
        if repo_path(path) in FRONTMATTER_EXEMPT_FILES:
            continue
        if path.name in FRONTMATTER_EXEMPT_BASENAMES:
            continue
        try:
            lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
        except OSError:
            continue
        if not lines or lines[0].strip() != "---":
            continue
        try:
            closing = lines[1:].index("---") + 1
        except ValueError:
            continue
        updated = None
        for line in lines[1:closing]:
            match = re.match(r"^updated\s*:\s*(\S+)", line)
            if match:
                updated = match.group(1)
                break
        if updated is None or not DATE_RE.match(updated):
            continue
        last = last_dates.get(relative)
        if last is not None and updated < last:
            findings.append(Finding(repo_path(path), f"updated {updated} is older than last git change {last}"))
    return findings


def strip_fenced_code(text: str) -> str:
    return re.sub(r"```.*?```", "", text, flags=re.DOTALL)


def strip_inline_code(text: str) -> str:
    return re.sub(r"`[^`\n]*`", "", text)


def normalize_link_target(raw_target: str) -> str:
    target = raw_target.strip()
    if target.startswith("<") and target.endswith(">"):
        target = target[1:-1].strip()
    if " " in target and not target.startswith("../") and not target.startswith("./"):
        target = target.split(" ", 1)[0]
    return unquote(target)


def markdown_link_targets(text: str) -> list[str]:
    targets: list[str] = []
    index = 0
    while index < len(text):
        open_bracket = text.find("[", index)
        if open_bracket == -1:
            break

        close_bracket = text.find("]", open_bracket + 1)
        if close_bracket == -1:
            break

        open_paren = close_bracket + 1
        if open_paren >= len(text) or text[open_paren] != "(":
            index = close_bracket + 1
            continue

        cursor = open_paren + 1
        depth = 1
        while cursor < len(text):
            char = text[cursor]
            if char == "\\":
                cursor += 2
                continue
            if char == "(":
                depth += 1
            elif char == ")":
                depth -= 1
                if depth == 0:
                    targets.append(text[open_paren + 1 : cursor])
                    break
            cursor += 1

        index = cursor + 1
    return targets


def is_local_link(target: str) -> bool:
    lowered = target.lower()
    if TRANSCRIPT_LINK_RE.match(target.strip()):
        return False
    return bool(target) and not target.startswith("#") and not lowered.startswith(LINK_SKIP_PREFIXES)


def strip_line_suffix(target: str) -> str:
    return re.sub(r":\d+(?::\d+)?$", "", target)


def resolve_link(source: Path, raw_target: str) -> Path | None:
    target = normalize_link_target(raw_target)
    if not is_local_link(target):
        return None
    target_without_anchor = strip_line_suffix(target.split("#", 1)[0])
    if not target_without_anchor:
        return None
    if target_without_anchor.startswith(str(REPO_ROOT) + "/"):
        return Path(target_without_anchor).resolve()
    if target_without_anchor.startswith("/"):
        return (REPO_ROOT / target_without_anchor.lstrip("/")).resolve()
    if target_without_anchor.startswith(ROOT_RELATIVE_LINK_PREFIXES):
        repo_target = (REPO_ROOT / target_without_anchor).resolve()
        if repo_target.exists():
            return repo_target
    return (source.parent / target_without_anchor).resolve()


# Docs-graph integrity only — plans often deep-link .kt/.tsx for navigation.
DOC_LINK_SUFFIXES = {".md", ".markdown", ".html", ".htm"}


def is_documentation_link_target(raw_target: str) -> bool:
    target = normalize_link_target(raw_target)
    path_part = strip_line_suffix(target.split("#", 1)[0]).rstrip("/")
    if not path_part:
        return False
    name = Path(path_part).name
    if "." not in name:
        # directory / bare path — treat as doc navigation
        return True
    suffix = Path(name).suffix.lower()
    return suffix in DOC_LINK_SUFFIXES


def link_findings(markdown_files: list[Path]) -> list[Finding]:
    findings: list[Finding] = []
    for path in markdown_files:
        if "templates" in path.relative_to(REPO_ROOT).parts:
            continue

        text = strip_inline_code(strip_fenced_code(path.read_text(encoding="utf-8", errors="replace")))
        for raw_target in markdown_link_targets(text):
            if not is_documentation_link_target(raw_target):
                continue
            target_path = resolve_link(path, raw_target)
            if target_path is None:
                continue
            if target_path.exists():
                continue
            findings.append(Finding(repo_path(path), f"broken local link: {raw_target}"))

    return findings


def autogenerated_marker_findings(markdown_files: list[Path]) -> list[Finding]:
    findings: list[Finding] = []
    for path in markdown_files:
        relative = repo_path(path)
        if relative in {"docs/DOCS-SPEC.md", "docs/DOCUMENTATION.md", "dev/plans/docs-governance-health-check.md"}:
            continue
        if relative.startswith("dev/plans/") or relative.startswith("dev/archive/"):
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        for marker in AUTOGENERATED_MARKERS:
            if marker in text:
                findings.append(Finding(relative, f"outdated generated-index marker remains: {marker}"))
                break
    return findings


def flatten_groups(groups: dict[str, list[Finding]]) -> list[Finding]:
    findings: list[Finding] = []
    for group_findings in groups.values():
        findings.extend(group_findings)
    return findings


def finding_to_dict(finding: Finding) -> dict[str, str]:
    return {
        "path": finding.path,
        "message": finding.message,
    }


def grouped_findings_to_dict(groups: dict[str, list[Finding]]) -> dict[str, list[dict[str, str]]]:
    return {
        name: [finding_to_dict(finding) for finding in findings]
        for name, findings in groups.items()
    }


def print_grouped_section(title: str, groups: dict[str, list[Finding]], max_details: int) -> None:
    total = len(flatten_groups(groups))
    print(f"{title}: {total}")
    for group_name, findings in groups.items():
        print(f"  {group_name}: {len(findings)}")
        for finding in findings[:max_details]:
            print(f"    - {finding.path}: {finding.message}")
        remaining = len(findings) - max_details
        if remaining > 0:
            print(f"    ... {remaining} more")


def print_json_report(
    *,
    result: str,
    markdown_files_checked: int,
    active_gradle_modules: int,
    error_groups: dict[str, list[Finding]],
    warning_groups: dict[str, list[Finding]],
    strict_frontmatter: bool,
    strict_links: bool,
) -> None:
    print(
        json.dumps(
            {
                "result": result,
                "markdown_files_checked": markdown_files_checked,
                "active_gradle_modules": active_gradle_modules,
                "strict_frontmatter": strict_frontmatter,
                "strict_links": strict_links,
                "counts": {
                    "errors": len(flatten_groups(error_groups)),
                    "warnings": len(flatten_groups(warning_groups)),
                },
                "errors": grouped_findings_to_dict(error_groups),
                "warnings": grouped_findings_to_dict(warning_groups),
            },
            ensure_ascii=False,
            indent=2,
            sort_keys=True,
        )
    )


def result_label(errors: list[Finding], warnings: list[Finding]) -> str:
    if errors:
        return "failed"
    if warnings:
        return "passed_with_warnings"
    return "passed"


def print_text_report(
    *,
    result: str,
    markdown_files_checked: int,
    active_gradle_modules: int,
    error_groups: dict[str, list[Finding]],
    warning_groups: dict[str, list[Finding]],
    max_details: int,
) -> None:
    print("Docs health check")
    print(f"- markdown files checked: {markdown_files_checked}")
    print(f"- active Gradle modules: {active_gradle_modules}")
    print()
    print_grouped_section("Errors", error_groups, max_details)
    print_grouped_section("Warnings", warning_groups, max_details)
    print()

    if result == "failed":
        print("Result: failed")
    elif result == "passed_with_warnings":
        print("Result: passed with warnings")
    else:
        print("Result: passed")


def add_group(groups: dict[str, list[Finding]], name: str, findings: list[Finding]) -> None:
    groups[name] = findings


def build_finding_groups(
    *,
    required_errors: list[Finding],
    status_md_size_errors: list[Finding],
    unreadable_markdown: list[Finding],
    module_errors: list[Finding],
    module_warnings: list[Finding],
    frontmatter: list[Finding],
    links: list[Finding],
    generated_markers: list[Finding],
    stale_updated: list[Finding],
    strict_frontmatter: bool,
    strict_links: bool,
) -> tuple[dict[str, list[Finding]], dict[str, list[Finding]]]:
    error_groups: dict[str, list[Finding]] = {}
    warning_groups: dict[str, list[Finding]] = {}

    add_group(error_groups, "required_entries", required_errors)
    add_group(error_groups, "status_md_size", status_md_size_errors)
    add_group(error_groups, "module_indexes", module_errors)
    add_group(warning_groups, "module_readmes", module_warnings)
    add_group(warning_groups, "unreadable_markdown", unreadable_markdown)
    add_group(warning_groups, "generated_markers", generated_markers)
    add_group(warning_groups, "stale_updated", stale_updated)

    if strict_frontmatter:
        add_group(error_groups, "frontmatter", frontmatter)
    else:
        add_group(warning_groups, "frontmatter", frontmatter)

    if strict_links:
        add_group(error_groups, "links", links)
    else:
        add_group(warning_groups, "links", links)

    return error_groups, warning_groups


def main() -> int:
    args = parse_args()
    markdown_files = iter_markdown_files()
    active_modules = parse_gradle_modules()

    required_errors = check_required_entries()
    status_md_size_errors = check_status_md_line_limit() + check_status_md_snapshot_body()
    merge_sha_errors = check_status_md_merge_sha_placeholder()
    unreadable_markdown = unreadable_markdown_findings()
    module_errors, module_warnings = check_module_indexes(active_modules)
    frontmatter = frontmatter_findings([*markdown_files, *iter_iteration_frontmatter_files()])
    links = link_findings(markdown_files)
    generated_markers = autogenerated_marker_findings(markdown_files)
    stale_updated = stale_updated_findings(markdown_files)

    error_groups, warning_groups = build_finding_groups(
        required_errors=required_errors + merge_sha_errors,
        status_md_size_errors=status_md_size_errors,
        unreadable_markdown=unreadable_markdown,
        module_errors=module_errors,
        module_warnings=module_warnings,
        frontmatter=frontmatter,
        links=links,
        generated_markers=generated_markers,
        stale_updated=stale_updated,
        strict_frontmatter=args.strict_frontmatter,
        strict_links=args.strict_links,
    )
    errors = flatten_groups(error_groups)
    warnings = flatten_groups(warning_groups)
    result = result_label(errors, warnings)

    if args.format == "json":
        print_json_report(
            result=result,
            markdown_files_checked=len(markdown_files),
            active_gradle_modules=len(active_modules),
            error_groups=error_groups,
            warning_groups=warning_groups,
            strict_frontmatter=args.strict_frontmatter,
            strict_links=args.strict_links,
        )
    else:
        print_text_report(
            result=result,
            markdown_files_checked=len(markdown_files),
            active_gradle_modules=len(active_modules),
            error_groups=error_groups,
            warning_groups=warning_groups,
            max_details=args.max_details,
        )

    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
